"""Generate the README results table from results/*.json (nothing typed by hand).

Prints the table, and with --write replaces the block between
<!-- results:start --> and <!-- results:end --> in README.md.
"""

import argparse
import json
from pathlib import Path
from typing import Any

R = Path("results")
START, END = "<!-- results:start -->", "<!-- results:end -->"


def load(name: str) -> Any:
    p = R / name
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def table() -> str:
    s = load("summary.json") or {}
    base = (load("baselines.json") or {}).get("baselines", [])
    e = s.get("engine", {})
    lines = [
        f"Real UCI #447 test split ({e.get('n_test_cycles', '?')} cycles, grouped by condition). "
        "Generated by `scripts/make_readme_table.py`.",
        "",
        "| Model | Mean macro-F1 | Cooler | Valve | Pump | Accumulator | Joint exact match | Claims verified |",
        "|---|---|---|---|---|---|---|---|",
    ]
    comps = ["cooler_condition", "valve_condition", "pump_leakage", "accumulator_pressure"]
    for b in base:
        if b.get("status") != "done":
            lines.append(f"| {b['label']} | not run | | | | | | {b.get('reason', '')} |")
            continue
        std = b.get("mean_macro_f1_std", 0.0)
        pm = f" ± {std:.3f}" if len(b.get("seeds", [])) > 1 else ""
        pc = " | ".join(f"{b['per_component'][k]:.3f}" for k in comps)
        lines.append(
            f"| {b['label']} | {b['mean_macro_f1']:.3f}{pm} | {pc} | "
            f"{b['joint_exact_match']:.3f} | — |"
        )
    if e:
        pc = " | ".join(f"{e['per_component'][k]['macro_f1']:.3f}" for k in comps)
        lines.append(
            f"| **Sightglass engine** (B1 + rationale engine) | **{e['mean_macro_f1']:.3f}** | {pc} | "
            f"{e['joint_exact_match']:.3f} | {e['verified_claims']}/{e['total_claims']} "
            f"(by construction) |"
        )
    t = s.get("tslm", {})
    lines.append(
        f"| Sightglass TSLM (OpenTSLM-Flamingo) | {t.get('status', 'pending')} | | | | | | "
        f"{t.get('reason', '')} |"
    )
    c = s.get("checker", {})
    if c:
        lines += [
            "",
            f"Checker validation: round trip {c['roundtrip_pct']:.1f}% of {c['roundtrip_claims']} "
            f"claims; ±20% value corruptions caught {c['corruption_caught_pct']:.1f}% "
            f"(n={c['n_corrupted']}); direction flips caught {c['direction_flip_caught_pct']:.1f}% "
            f"(n={c['n_direction_flipped']}). Label–evidence consistency of the engine: "
            f"{e.get('consistency_pct', 0):.1f}%.",
        ]
    for a in s.get("ablations", []):
        lines.append(
            f"- {a['label']}: mean macro-F1 {a['mean_macro_f1']:.3f} "
            f"({a['delta_mean_macro_f1']:+.3f} vs B1)."
        )
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    t = table()
    print(t)
    if args.write:
        readme = Path("README.md")
        text = readme.read_text(encoding="utf-8")
        if START in text and END in text:
            head, rest = text.split(START, 1)
            _, tail = rest.split(END, 1)
            readme.write_text(f"{head}{START}\n{t}\n{END}{tail}", encoding="utf-8")


if __name__ == "__main__":
    main()
